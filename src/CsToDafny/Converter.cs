using CsToDafny.Dafny;
using CsToDafny.Translation;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace CsToDafny;

public sealed record SourceFile(string Path, string Text);

public sealed record ConversionResult(string Dafny, IReadOnlyList<ConversionDiagnostic> Diagnostics)
{
    public bool HasErrors => Diagnostics.Any(d => d.Severity == Severity.Error);
}

/// <summary>Converts C# source into a Dafny program suitable for verification.</summary>
public static class Converter
{
    public static ConversionResult Convert(string csharp, ConverterOptions? options = null) =>
        Convert([new SourceFile("input.cs", csharp)], options);

    public static ConversionResult Convert(IEnumerable<SourceFile> sources, ConverterOptions? options = null)
    {
        options ??= new ConverterOptions();
        var parseOptions = new CSharpParseOptions(LanguageVersion.Preview);
        var trees = sources.Select(s => CSharpSyntaxTree.ParseText(s.Text, parseOptions, s.Path)).ToList();
        var compilation = CSharpCompilation.Create(
            "Input",
            trees,
            References(options),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
        return Convert(compilation, options);
    }

    /// <summary>
    /// Convert an existing compilation, e.g. one loaded from a .csproj so that package and project
    /// references bind. The project's own nullable setting is respected.
    /// </summary>
    public static ConversionResult Convert(CSharpCompilation compilation, ConverterOptions? options = null)
    {
        options ??= new ConverterOptions();
        var diags = new Diagnostics();
        var errors = compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToList();
        foreach (var error in errors.Take(20))
        {
            diags.Add(Severity.Warning, $"C# compile error (translation may be incomplete): {error.GetMessage()}",
                error.Location.SourceTree?.GetRoot().FindNode(error.Location.SourceSpan));
        }
        if (errors.Count > 20)
            diags.Add(Severity.Warning, $"{errors.Count - 20} more C# compile errors not shown", null);
        if (compilation.Options.NullableContextOptions == NullableContextOptions.Disable)
            diags.Add(Severity.Warning, "nullable reference types are disabled: reference types are assumed non-null", null);

        var symbols = new SymbolModel(compilation);
        foreach (var f in symbols.ForcedNullableFields)
            diags.Add(Severity.Warning, $"field {f} made nullable: the record refers back to itself, so in C# the chain must end with null", null);
        var selection = new Selection(symbols, options.Include);
        // Outside the selection, members of stateful classes are integrations: model them as effectful methods.
        Classifier.Classify(symbols, m => !m.IsStatic && !selection.IsIncluded(m.ContainingType) &&
                                          m.ContainingType.TypeKind == TypeKind.Class && symbols.DatatypeOf(m.ContainingType) is null);
        var types = new TypeTranslator(symbols, options, diags);
        var decls = new DeclTranslator(symbols, types, diags, options, selection).Translate();

        var module = new ModuleDecl(options.ModuleName, ["opened " + Prelude.ModuleName], decls);
        var header = "// Generated by cs2dfy from C# source. Edit the C#, or treat this file as a starting point for specification.\n\n";
        var text = header + Printer.Print([new RawDecl(Prelude.Text), module]);
        return new ConversionResult(text, diags.Items);
    }

    private static IEnumerable<MetadataReference> References(ConverterOptions options)
    {
        var tpa = (AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") as string ?? "").Split(Path.PathSeparator, StringSplitOptions.RemoveEmptyEntries);
        foreach (var path in tpa.Concat(options.References))
            yield return MetadataReference.CreateFromFile(path);
    }
}
